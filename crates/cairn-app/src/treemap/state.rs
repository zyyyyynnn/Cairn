/// Process-wide request epoch. A response for a directory the view has already
/// left must never write into the next directory, even across a replaced view.
static TREEMAP_REQUEST_EPOCH: AtomicU64 = AtomicU64::new(0);

pub(super) fn next_tree_request_epoch() -> u64 {
    TREEMAP_REQUEST_EPOCH.fetch_add(1, Ordering::Relaxed) + 1
}

/// Why the service could not provide a Treemap directory. The reason chooses
/// the one-line state copy and whether another request can help.
#[derive(Clone, Copy, Debug, PartialEq, Eq)]
pub(crate) enum TreemapUnavailable {
    NotIndexed,
    NotDirectory,
    TooLarge,
    ServiceUnavailable,
}

impl TreemapUnavailable {
    pub(crate) const fn message_key(self) -> &'static str {
        match self {
            Self::NotIndexed => "treemap_unavailable_not_indexed",
            Self::NotDirectory => "treemap_unavailable_not_directory",
            Self::TooLarge => "treemap_unavailable_too_large",
            Self::ServiceUnavailable => "treemap_unavailable_service",
        }
    }

    pub(crate) const fn retryable(self) -> bool {
        matches!(self, Self::NotIndexed | Self::ServiceUnavailable)
    }
}

pub(crate) fn tree_unavailable_from_code(code: u32) -> TreemapUnavailable {
    match code {
        ERROR_CODE_TREE_NOT_INDEXED => TreemapUnavailable::NotIndexed,
        ERROR_CODE_TREE_NOT_DIRECTORY => TreemapUnavailable::NotDirectory,
        ERROR_CODE_TREE_TOO_LARGE => TreemapUnavailable::TooLarge,
        _ => TreemapUnavailable::ServiceUnavailable,
    }
}

/// State for the drive disk space Treemap visualization.
pub struct TreemapViewState {
    drive: char,
    navigation: TreemapNavigation,
    /// Full hierarchical tree node for the current directory, shared with the
    /// drive cache while the view shows the tree a finished scan produced.
    /// Scan folding writes through `Arc::make_mut`, so sharing never copies
    /// until a mutation actually needs a private tree.
    pub(super) root_tree: Option<Arc<TreemapTreeNode>>,
    /// Cached full drive root tree once scanned (enables 0ms in-memory drill-down/up).
    /// Shares the allocation with `root_tree` when the view shows the drive
    /// root, so a finished tree is held once, not twice.
    stored_drive_tree: Option<Arc<TreemapTreeNode>>,
    /// Cached directory trees for drilled subdirectories fetched from the service.
    cached_dir_trees: TreemapLru<String, Arc<TreemapTreeNode>>,
    /// Calculated rectangular layout nodes (hierarchical nested)
    pub(super) layout_nodes: Vec<NestedTreemapLayoutNode>,
    /// The canvas root's folded tail when it cannot carry a tile label. The path
    /// band hosts it; the body keeps its area for label-sized tiles.
    pub(super) root_tail: Option<TreemapTail>,
    /// A context menu is open: hover tooltips stay hidden while the menu is active so a
    /// tooltip cannot cover the menu.
    pub(super) suppress_tooltip: bool,
    /// Level of detail (1 to 5, default 5)
    pub(super) detail_level: usize,
    /// Full path of the selected node. Ids are regenerated by every progressive
    /// scan and can collide, so the path is the only stable identity.
    pub(super) selected_path: Option<String>,
    /// Which categories stay at full strength. Filtered categories are dimmed
    /// in place so the spatial layout and selection path never move.
    /// Total aggregated size of all items currently displayed in the view
    current_dir_total_size: u64,
    /// Total number of items under the current Treemap root, at every depth.
    /// Cache and service loads take it from the index; a navigation keeps it in step
    /// with the discovered files and directories.
    current_dir_total_items: usize,
    /// Focus handle for keyboard events (Backspace, Enter)
    pub(super) focus: Option<FocusHandle>,
    /// Generation identifier for layout and surface reveal animation.
    pub(super) reveal_generation: u64,
    /// Bounds used by the current squarified layout. Sidebar width changes are
    /// projected onto it instead of triggering another layout.
    pub(super) last_bounds: (f32, f32),
    /// Last whole-window size, so a real window resize recomputes the layout
    /// while a sidebar-driven canvas change stays a projection.
    pub(super) last_window_size: (f32, f32),
    /// Last observed window scale factor for device-pixel snapping.
    pub(super) last_scale_factor: f32,
    /// Actual canvas bounds published by the paint callback, used by pointer pan and wheel zoom
    /// instead of window-chrome subtraction once the canvas has painted its first frame.
    pub(super) painted_canvas_bounds: Rc<Cell<Option<Bounds<Pixels>>>>,
    /// Generation counter for the scan/load overlay fade-out animation.
    pub(crate) scan_fade_epoch: u64,
    /// Highest scan fade epoch for which a cleanup timer has been scheduled.
    pub(crate) scan_fade_timer_armed: u64,
    /// Whether a service tree request is in flight.
    pub(super) is_scanning: bool,
    /// Epoch of the directory request the view is waiting for. A late answer
    /// for an older directory is ignored.
    pub(super) request_epoch: u64,
    /// The service could not provide the current directory; this is not a legitimate empty folder.
    pub(super) unavailable: Option<TreemapUnavailable>,
    /// Whether a complete tree has been computed and revealed on the canvas.
    /// Reset on each new directory request until the tree is ready.
    pub(super) content_revealed: bool,
    /// Exact item totals from scans completed in this view, keyed by directory.
    /// A later stored-tree load of the same directory reuses the scan total
    /// instead of the depth-capped tree count.
    scanned_item_totals: TreemapLru<String, usize>,
    /// Wheel zoom transform. The layout above stays in base pixel space.
    pub(super) zoom: TreemapZoom,
}

fn normalize_dir_key(path: &str) -> String {
    path.trim_end_matches(['\\', '/']).to_ascii_uppercase()
}

impl TreemapViewState {
    pub(super) fn new(drive: char, entry_dir: &str, focus: FocusHandle) -> (Self, Option<PathBuf>) {
        let drive_upper = drive.to_ascii_uppercase();
        let mut state = Self::new_headless(drive_upper);
        state.navigation = TreemapNavigation::at_directory(drive_upper, entry_dir);
        state.focus = Some(focus.tab_stop(true));

        let scan_target = state.load_current_dir();
        (state, scan_target)
    }

    pub(super) fn canvas_origin(&self, fallback: (f32, f32)) -> (f32, f32) {
        self.painted_canvas_bounds
            .get()
            .filter(|bounds| {
                f32::from(bounds.size.width) > 0.0 && f32::from(bounds.size.height) > 0.0
            })
            .map(|bounds| (f32::from(bounds.origin.x), f32::from(bounds.origin.y)))
            .unwrap_or(fallback)
    }

    /// Creates a windowless treemap state rooted at `drive` without reading focus handles.
    pub(super) fn new_headless(drive: char) -> Self {
        let drive_upper = drive.to_ascii_uppercase();
        Self {
            drive: drive_upper,
            navigation: TreemapNavigation::at_drive_root(drive_upper),
            root_tree: None,
            stored_drive_tree: None,
            cached_dir_trees: TreemapLru::with_capacity(MAX_CACHED_DIR_TREES),
            layout_nodes: Vec::new(),
            root_tail: None,
            detail_level: 5,
            suppress_tooltip: false,
            selected_path: None,
            current_dir_total_size: 0,
            current_dir_total_items: 0,
            focus: None,
            reveal_generation: 0,
            last_bounds: (800.0, 600.0),
            last_window_size: (0.0, 0.0),
            last_scale_factor: 1.0,
            painted_canvas_bounds: Rc::new(Cell::new(None)),
            scan_fade_epoch: 0,
            scan_fade_timer_armed: 0,
            is_scanning: false,
            request_epoch: 0,
            unavailable: None,
            content_revealed: false,
            scanned_item_totals: TreemapLru::with_capacity(MAX_SCANNED_ITEM_TOTALS),
            zoom: TreemapZoom::new(),
        }
    }

    pub(super) fn focus_handle(&self) -> Option<&FocusHandle> {
        self.focus.as_ref()
    }

    pub(super) fn request_focus(&self, window: &mut Window, cx: &mut App) {
        if let Some(ref focus) = self.focus {
            focus.focus(window, cx);
        }
    }

    pub fn current_dir(&self) -> &str {
        self.navigation.current_dir()
    }

    pub fn can_go_back(&self) -> bool {
        self.navigation.can_go_back()
    }

    pub fn can_go_forward(&self) -> bool {
        self.navigation.can_go_forward()
    }

    pub fn can_go_up(&self) -> bool {
        self.navigation.can_go_up()
    }

    pub fn clear_selection(&mut self) -> bool {
        self.selected_path.take().is_some()
    }

    /// Loads the current directory from the stored trees.
    /// Returns `Some(path)` when the service has to answer, or `None` when the
    /// in-memory trees already hold the directory.
    fn load_current_dir(&mut self) -> Option<PathBuf> {
        // Every navigation starts from the whole-canvas view.
        self.zoom.reset_view();
        self.reset_scan_state();
        self.selected_path = None;
        self.suppress_tooltip = false;

        let current_dir = self.navigation.current_dir().to_string();

        // 1. Drive root: instant from stored_drive_tree if already scanned.
        if is_drive_root(&current_dir) {
            if let Some(drive_tree) = self.stored_drive_tree.clone() {
                self.current_dir_total_items = self
                    .scanned_item_totals
                    .get(&current_dir)
                    .copied()
                    .unwrap_or_else(|| drive_tree.descendant_count());
                self.adopt_shared_tree(drive_tree);
                self.reveal_content();
                return None;
            }
        } else {
            // 2. Subdirectory: check if we previously fetched and cached the full tree for this directory.
            let dir_key = normalize_dir_key(&current_dir);
            if let Some(cached_tree) = self.cached_dir_trees.get(&dir_key).cloned() {
                self.current_dir_total_items = self
                    .scanned_item_totals
                    .get(&current_dir)
                    .copied()
                    .unwrap_or_else(|| cached_tree.descendant_count());
                self.adopt_shared_tree(cached_tree);
                self.reveal_content();
                return None;
            }
        }

        // 3. The service's live index has to answer before the canvas can draw.
        self.current_dir_total_size = 0;
        self.current_dir_total_items = 0;
        self.is_scanning = true;

        Some(PathBuf::from(current_dir))
    }

    /// Starts a new directory request from nothing to draw. The fresh epoch makes a late answer
    /// for the directory being left unrenderable, and the cleared tree cannot outlive its root.
    pub(super) fn reset_scan_state(&mut self) {
        self.request_epoch = next_tree_request_epoch();
        self.is_scanning = false;
        self.unavailable = None;
        self.content_revealed = false;
        self.layout_nodes.clear();
        self.root_tail = None;
        self.root_tree = None;
    }

    /// Adopts a tree the scanner already aggregated and sorted.
    fn set_prepared_tree(&mut self, tree: TreemapTreeNode) {
        self.current_dir_total_size = tree.size;
        self.current_dir_total_items = tree.descendant_count();
        self.root_tree = Some(Arc::new(tree));
        self.recompute_layout();
    }

    /// Adopts an already finished, aggregated and sorted tree without copying
    /// it. The drive-root view and the cache then share one allocation.
    fn adopt_shared_tree(&mut self, tree: Arc<TreemapTreeNode>) {
        self.current_dir_total_size = tree.size;
        self.root_tree = Some(tree);
        self.recompute_layout();
    }

    /// Marks the scanned tree content as ready for display.
    pub(super) fn reveal_content(&mut self) {
        self.content_revealed = true;
        self.reveal_generation = self.reveal_generation.wrapping_add(1);
        self.scan_fade_epoch = self.reveal_generation;
    }

    /// The service could not answer for this directory. The canvas shows the
    /// unavailable message instead of a misleading empty folder.
    pub(super) fn mark_unavailable(&mut self, reason: TreemapUnavailable) {
        self.is_scanning = false;
        self.unavailable = Some(reason);
        self.content_revealed = true;
        self.root_tree = None;
        self.layout_nodes.clear();
        self.root_tail = None;
        self.current_dir_total_size = 0;
        self.current_dir_total_items = 0;
    }

    /// Adopts a tree the service's live volume index answered with. The flat
    /// pre-order wire entries are reassembled structurally; aggregation,
    /// sorting and categories were already applied by the producer
    /// (`DirectorySizeIndex::build_tree_node` runs the same finish pipeline as
    /// a scan), so no second pass runs here.
    pub(super) fn adopt_service_tree(&mut self, entries: Vec<TreeEntryData>) -> bool {
        self.unavailable = None;
        let Some(tree) = reassemble_tree(entries) else {
            return false;
        };
        let descendant_count = tree.descendant_count();
        self.current_dir_total_items = descendant_count;
        self.set_prepared_tree(tree);
        let current_dir = self.navigation.current_dir().to_string();
        if is_drive_root(&current_dir) {
            self.stored_drive_tree = self.root_tree.clone();
        } else if let Some(ref tree) = self.root_tree {
            self.cached_dir_trees
                .insert(normalize_dir_key(&current_dir), tree.clone());
        }
        self.scanned_item_totals
            .insert(current_dir, descendant_count);
        self.is_scanning = false;
        self.reveal_content();
        true
    }

    /// Recomputes Treemap nested layout nodes according to current bounds and detail level.
    pub(super) fn recompute_layout(&mut self) {
        let (w, h) = self.last_bounds;
        // The gutter is a device-pixel quantity, so the canvas edge is inset by half of it in the
        // same units the tiles use; a logical inset here would leave that one margin a pixel
        // thinner than every seam inside the canvas.
        let scale = self.last_scale_factor;
        let inset = painted_gutter_device(scale) / (2.0 * scale);
        let bounds = TreemapRect::new(
            inset,
            inset,
            (w - 2.0 * inset).max(50.0),
            (h - 2.0 * inset).max(50.0),
        );
        let options = NestedTreemapOptions::from_detail_level(self.detail_level);

        // The tree carries names only, so the layout materializes tile paths
        // from the directory the view is rooted at.
        let parent = self.navigation.current_dir().to_string();
        if let Some(ref tree) = self.root_tree {
            let laid = layout_nested_treemap(&tree.children, &parent, bounds, &options, 0);
            self.layout_nodes = laid.nodes;
            self.root_tail = laid.tail;
        } else {
            self.layout_nodes.clear();
            self.root_tail = None;
        }
        // A resize or detail change can fold the selected block into a tail or
        // remove it; the canvas must not stay dimmed around a node it can no
        // longer resolve. A tail is an entry in a header, not a tile body, and
        // cannot own the focus the dimming expresses.
        if let Some(ref selected) = self.selected_path {
            if self.layout_node(selected).is_none() {
                self.selected_path = None;
            }
        }
        // A recompute starts from the layout's own width. The render pass then
        // adopts the projection that fits the current sidebar-driven canvas.
        self.zoom.set_stretch_x(1.0, (w, h));
    }

    pub(super) fn set_detail_level(&mut self, level: usize) {
        let clamped = level.clamp(1, 5);
        if self.detail_level != clamped {
            self.detail_level = clamped;
            self.zoom.reset_view();
            self.recompute_layout();
            self.reveal_content();
        }
    }

    /// Zoom percentage the status bar shows, rounded up. Identity reports
    /// `None` so the reset badge only exists while there is something to reset.
    pub fn zoom_percent(&self) -> Option<u32> {
        self.zoom.zoom_percent()
    }

    pub fn is_panning(&self) -> bool {
        self.zoom.is_panning()
    }

    pub(crate) fn end_pan(&mut self) -> bool {
        self.zoom.end_pan()
    }

    /// Drills down into the specified subdirectory path.
    pub(super) fn drill_down(&mut self, target_path: &str) -> Option<PathBuf> {
        self.navigation.enter(target_path);
        self.load_current_dir()
    }

    /// Drills up to the parent directory as a history step.
    pub(super) fn drill_up(&mut self) -> Option<PathBuf> {
        if !self.navigation.up() {
            return None;
        }
        self.load_current_dir()
    }

    /// Returns to the directory most recently left by a drill or [`Self::drill_up`].
    pub(super) fn drill_back(&mut self) -> Option<PathBuf> {
        if !self.navigation.back() {
            return None;
        }
        self.load_current_dir()
    }

    /// Returns to the directory most recently left by Back, keeping older
    /// departures for the Forward after it.
    pub(super) fn drill_forward(&mut self) -> Option<PathBuf> {
        if !self.navigation.forward() {
            return None;
        }
        self.load_current_dir()
    }

    /// The laid-out node with this path, for the summary-block hand-off.
    pub(crate) fn layout_node(&self, path: &str) -> Option<&NestedTreemapLayoutNode> {
        find_node_by_path(&self.layout_nodes, path)
    }

    /// The folded tail with this path, whether it belongs to the canvas root or
    /// to a nested directory header.
    pub(crate) fn tail_by_path(&self, path: &str) -> Option<&TreemapTail> {
        fn search<'a>(nodes: &'a [NestedTreemapLayoutNode], path: &str) -> Option<&'a TreemapTail> {
            nodes.iter().find_map(|node| {
                node.tail
                    .as_ref()
                    .filter(|tail| tail.path == path)
                    .or_else(|| search(&node.children, path))
            })
        }
        self.root_tail
            .as_ref()
            .filter(|tail| tail.path == path)
            .or_else(|| search(&self.layout_nodes, path))
    }

    /// The children of `parent_path` in the tree the canvas is showing.
    pub(crate) fn children_at(&self, parent_path: &str) -> &[TreemapTreeNode] {
        let Some(tree) = self.root_tree.as_deref() else {
            return &[];
        };
        let Some(remaining) = relative_segments(self.navigation.current_dir(), parent_path) else {
            return &[];
        };
        let mut node = tree;
        for segment in remaining {
            match node
                .children
                .iter()
                .find(|child| child.name.eq_ignore_ascii_case(segment))
            {
                Some(child) => node = child,
                None => return &[],
            }
        }
        &node.children
    }

    pub fn selected_node(&self) -> Option<&NestedTreemapLayoutNode> {
        let selected_path = self.selected_path.as_deref()?;
        find_node_by_path(&self.layout_nodes, selected_path)
    }

    /// A selectable aggregate is a summary, not a filesystem object: it has no
    /// path that can be opened, revealed or copied.
    pub fn selected_real_path(&self) -> Option<&str> {
        let node = self.selected_node()?;
        (!node.is_aggregate()).then_some(node.path.as_str())
    }

    /// Total aggregated byte size of the current Treemap root.
    pub fn total_size(&self) -> u64 {
        self.current_dir_total_size
    }

    /// Total items under the current Treemap root at every depth, files and
    /// directories each counted once. Matches the recursive byte total shown
    /// beside it; aggregate blocks fold items visually, not in this count.
    pub fn total_items(&self) -> usize {
        self.current_dir_total_items
    }

    /// Whether the service is still answering for the current directory.
    pub fn is_scanning(&self) -> bool {
        self.is_scanning
    }

    /// The service could not provide the current root; the empty canvas is a
    /// failure, not an empty folder.
    pub fn is_unavailable(&self) -> bool {
        self.unavailable.is_some()
    }

    pub(crate) fn unavailable_reason(&self) -> Option<TreemapUnavailable> {
        self.unavailable
    }

    /// Removes one item from the in-memory tree after the shell deleted it on
    /// disk, so the canvas reflects the deletion without a rescan. The shared
    /// drive cache is re-pointed when this view holds the cached root, and a
    /// selection on the removed path is dropped.
    pub fn remove_item(&mut self, target_path: &str) {
        let current_dir = self.navigation.current_dir().to_string();
        let current_dir_key = normalize_dir_key(&current_dir);
        let drive_root = format!("{}:\\", self.drive);
        let at_drive_root = is_drive_root(&current_dir);

        // Drop duplicate Arc strong references held by caches before `Arc::make_mut` so
        // removing a deleted entry mutates the root allocation in-place without deep cloning.
        let restore_drive_tree = at_drive_root
            && self
                .stored_drive_tree
                .as_ref()
                .zip(self.root_tree.as_ref())
                .is_some_and(|(stored, root)| Arc::ptr_eq(stored, root));
        if restore_drive_tree {
            self.stored_drive_tree = None;
        }
        let had_dir_cache = self.cached_dir_trees.remove(&current_dir_key).is_some();

        let mut removed_count = None;

        // 1. If target_path is under the current view directory, remove it from root_tree
        if let Some((segments, name)) = resolve_relative_segments(&current_dir, target_path) {
            if let Some(tree) = self.root_tree.as_mut() {
                let tree = Arc::make_mut(tree);
                if let Some(count) = remove_below(tree, &segments, name) {
                    removed_count = Some(count);
                    tree.compute_aggregated_sizes();
                    tree.sort_recursive();
                    tree.propagate_content_categories();
                    self.current_dir_total_size = tree.size;
                    self.current_dir_total_items = tree.descendant_count();
                }
            }
        }

        // 2. Also restore or update stored_drive_tree
        if at_drive_root {
            if restore_drive_tree || removed_count.is_some() {
                self.stored_drive_tree = self.root_tree.clone();
            }
        } else if let Some(drive_tree) = self.stored_drive_tree.as_mut() {
            if let Some((drive_segments, drive_name)) =
                resolve_relative_segments(&drive_root, target_path)
            {
                let drive_tree = Arc::make_mut(drive_tree);
                if let Some(count) = remove_below(drive_tree, &drive_segments, drive_name) {
                    removed_count.get_or_insert(count);
                    drive_tree.compute_aggregated_sizes();
                    drive_tree.sort_recursive();
                    drive_tree.propagate_content_categories();
                }
            }
        }

        let Some(count) = removed_count else {
            if had_dir_cache {
                if let Some(ref tree) = self.root_tree {
                    self.cached_dir_trees.insert(current_dir_key, tree.clone());
                }
            }
            return;
        };

        self.cached_dir_trees.clear();

        // Keep cached scan totals updated for ancestors, drop deleted subtrees,
        // and avoid double-decrementing the current directory.
        self.scanned_item_totals.retain(|dir, total| {
            if path_is_within(dir, target_path) {
                // The directory or its ancestor was deleted
                false
            } else if same_directory(dir, &current_dir) {
                *total = self.current_dir_total_items;
                true
            } else if path_is_within(target_path, dir) {
                // Ancestor directory of deleted target
                *total = total.saturating_sub(count);
                true
            } else {
                // Unrelated directory
                true
            }
        });
        self.scanned_item_totals
            .insert_if_absent(current_dir, self.current_dir_total_items);

        if let Some(ref sel) = self.selected_path {
            if path_is_within(sel, target_path) {
                self.selected_path = None;
            }
        }
        self.recompute_layout();
    }
}

/// Extracts the relative subdirectory path segments and file/folder name from
/// `target_path` under `base_dir`. Returns `None` if `target_path` is not inside
/// `base_dir`.
fn resolve_relative_segments<'a>(
    base_dir: &str,
    target_path: &'a str,
) -> Option<(Vec<&'a str>, &'a str)> {
    let remaining = relative_segments(base_dir, target_path)?;
    let (&name, segments) = remaining.split_last()?;
    Some((segments.to_vec(), name))
}

/// Removes the child named `name` from `node` when `segments` is empty, or
/// descends the directory the first segment names and continues. Returns
/// `Some(removed_item_count)` when a child was found and removed.
fn remove_below(node: &mut TreemapTreeNode, segments: &[&str], name: &str) -> Option<usize> {
    let Some((segment, rest)) = segments.split_first() else {
        if let Some(index) = node
            .children
            .iter()
            .position(|child| child.name.eq_ignore_ascii_case(name))
        {
            let removed = node.children.remove(index);
            let count = 1 + removed.descendant_count();
            node.descendant_items = node.descendant_items.saturating_sub(count);
            if node.children.is_empty() {
                node.size = 0;
                node.descendant_items = 0;
            }
            return Some(count);
        }
        return None;
    };
    let index = node
        .children
        .iter()
        .position(|child| child.is_dir && child.name.eq_ignore_ascii_case(segment))?;
    if let Some(count) = remove_below(&mut node.children[index], rest, name) {
        node.descendant_items = node.descendant_items.saturating_sub(count);
        if node.children[index].children.is_empty() {
            node.children[index].size = 0;
            node.children[index].descendant_items = 0;
        }
        Some(count)
    } else {
        None
    }
}

fn find_node_by_path<'a>(
    nodes: &'a [NestedTreemapLayoutNode],
    path: &str,
) -> Option<&'a NestedTreemapLayoutNode> {
    for n in nodes {
        if n.path == path {
            return Some(n);
        }
        if let Some(found) = find_node_by_path(&n.children, path) {
            return Some(found);
        }
    }
    None
}

/// Rebuilds a tree from pre-order wire entries: an entry attaches as the next
/// child of the deepest open node shallower than it. `None` when the entries
/// do not start with a depth-0 root.
fn reassemble_tree(entries: Vec<TreeEntryData>) -> Option<TreemapTreeNode> {
    let mut iter = entries.into_iter();
    let root_entry = iter.next().filter(|entry| entry.depth == 0)?;
    let mut stack: Vec<TreemapTreeNode> = vec![node_from_entry(root_entry)];

    for entry in iter {
        // Stack position i always holds a depth-i node, so a depth-d entry
        // attaches under the node at index d-1: pop until d nodes remain,
        // then push. Pre-order from the producer only ever steps +1, but a
        // broken stream must be rejected, not silently re-parented.
        if stack.len() < entry.depth {
            return None;
        }
        while stack.len() > entry.depth {
            let child = stack.pop()?;
            stack.last_mut()?.children.push(child);
        }
        stack.push(node_from_entry(entry));
    }
    while stack.len() > 1 {
        let child = stack.pop()?;
        stack.last_mut()?.children.push(child);
    }
    stack.into_iter().next()
}

fn node_from_entry(entry: TreeEntryData) -> TreemapTreeNode {
    let mut node = if entry.is_dir {
        TreemapTreeNode::new_dir(0, entry.name, entry.modified_ts)
    } else {
        TreemapTreeNode::new_file(0, entry.name, entry.size, entry.modified_ts)
    };
    node.size = entry.size;
    node.descendant_items = entry.descendant_items;
    node
}

